const router = require('express').Router();
const auth = require('../middleware/auth');
const controller = require('../controllers/investmentController');
router.use(auth);
router.get('/gold-price', controller.goldPrice);
router.get('/', controller.list);
router.post('/', controller.create);
router.post('/:id/sell', controller.sell);
router.post('/:id/buy-more', controller.buyMore);
router.put('/:id/batches/:batchId', controller.updateBatch);
router.delete('/:id/batches/:batchId', controller.deleteBatch);
router.put('/:id', controller.update);
router.delete('/:id', controller.remove);
module.exports = router;
